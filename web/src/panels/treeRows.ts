import { useMemo } from "react";
import type { NodeSummary } from "../api/types";
import { useStore } from "../state/store";
import { useWorkspace } from "../workspace/store";
import { arrangeTree } from "../workspace/tree";
import { decorateTree } from "./stageTreeModel";
import { findDetailsRow } from "./detailsRow";
import { useMeshContext } from "./meshRun";

/**
 * The tree's DECORATED rows, as the tree itself builds them.
 *
 * **Its own module because two components need the same answer**: the tree draws these rows, and the
 * Details pane has to look up a row that is not a node (a run, a field, a placeholder) to know which
 * page to show. Computing them twice would let the two disagree the first time a decoration changed.
 *
 * The inputs are all store or workspace values, read here rather than passed, so a caller cannot
 * forget one - a missing `runs` would silently drop every run row from the pane's view of the tree.
 */
export function useTreeRows(): NodeSummary | null {
  const tree = useStore((s) => s.tree);
  const kinds = useStore((s) => s.conditionKinds);
  const runs = useStore((s) => s.run.runs);
  const resultsData = useStore((s) => s.results.data);
  const resultsView = useStore((s) => s.results.view);
  const setup = useStore((s) => s.setup);
  const tasksReply = useStore((s) => s.meshTasks);
  const groupOrder = useWorkspace((s) => s.document.tree.groupOrder);
  const hiddenGroups = useWorkspace((s) => s.document.tree.hidden);
  return useMemo(
    () =>
      arrangeTree(
        decorateTree(tree, {
          kinds,
          runs,
          results: { data: resultsData, view: resultsView },
          setup,
          tasks: tasksReply,
        }),
        groupOrder,
        hiddenGroups,
      ),
    [tree, kinds, runs, resultsData, resultsView, setup, tasksReply, groupOrder, hiddenGroups],
  );
}

/**
 * Find a row by id in a decorated tree, **including rows that are not nodes**.
 *
 * `findNode` walks the raw tree and returns null for a virtual row, which is exactly the case this
 * exists for: the gui-v3 review's warning 2 says the pane must work for virtual rows, and measured, a
 * selected run showed the stage checklist instead of the run.
 */
export function findShownRow(root: NodeSummary | null, id: string | null): NodeSummary | null {
  if (root === null || id === null) return null;
  if (root.id === id) return root;
  for (const child of root.children ?? []) {
    const hit = findShownRow(child, id);
    if (hit !== null) return hit;
  }
  return null;
}

/** Outline pages are generated by the outline, so a decorated-tree lookup alone cannot find them. */
export function useDetailsRow(id: string | null): NodeSummary | null {
  const root = useTreeRows();
  const expanded = useStore((s) => s.expanded);
  const layout = useWorkspace((s) => s.document.tree.layout);
  const hidden = useWorkspace((s) => s.document.tree.hidden);
  const meshers = useMeshContext((s) => s.meshers);
  return useMemo(() => findDetailsRow(root, id, layout, expanded, meshers.filter((m) => m.built), hidden), [root, id, layout, expanded, meshers, hidden]);
}
