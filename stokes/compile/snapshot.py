"""What the solver needs, as a plain immutable record (ADR-0008, T-212).

**A snapshot, not the model.** The writer takes this and nothing else, which is what makes the
case a pure
function of it: no tree, no session, no host. T-214 builds one of these from the project and
runs the
result; a test builds one by hand.

Frozen, because a case that changes while it is being written is a bug that would show up as a
file whose
two halves came from different runs. `write` on equal snapshots returns equal trees.
"""

from __future__ import annotations

from dataclasses import dataclass, field

#: The condition kinds this writer can express (docs/05 §2). Anything else is `compile.unsupported`,
#: which is deliberate: a silently wrong boundary condition is far worse than a refusal.
KINDS: tuple[str, ...] = (
    "velocity_inlet",
    "mass_flow_inlet",
    "pressure_outlet",
    "wall",
    "slip_wall",
    "symmetry",
    "unassigned",
    # The 2D front/back patches (ADR-0031): the mesher makes them and the solve snapshot gives
    # them their own kind whatever boundary names them, so a user cannot reassign them.
    "empty",
    "wedge",
)

#: The 2D patch types (ADR-0031): a patch of one of these mesh types takes the kind of the same
#: name. `empty` is the planar front/back (and an axisymmetric case's collapsed axis), `wedge` the
#: two sides of an axisymmetric wedge.
TWO_D_PATCH_TYPES: tuple[str, ...] = ("empty", "wedge")

#: The kinds whose field entry is just the mesh patch's own constraint type (`type symmetryPlane;`,
#: `type empty;`, `type wedge;`) in every field, and which carry no temperature condition.
CONSTRAINT_KINDS: tuple[str, ...] = ("symmetry", "empty", "wedge")

#: The mesh patch type used for planar `symmetry` boundaries generated by blockMesh. Snappy can
#: also use `SYMMETRY_PATCH_TYPE_NONPLANAR` when the CAD surface is curved. The field writer matches
#: whichever patch type the mesher generated.
#: Max non-orthogonality, degrees, above which the case limits the non-orthogonal correction
#: (`SolveSnapshot.non_orthogonal`); the project's own mesh quality bar is also 70.
NON_ORTHO_LIMIT = 70.0

SYMMETRY_PATCH_TYPE = "symmetryPlane"

#: Snappy surfaces may be curved. OpenFOAM's `symmetry` patch supports non-planar/multi-plane
#: faces and requires a matching `symmetry` field type.
SYMMETRY_PATCH_TYPE_NONPLANAR = "symmetry"


@dataclass(frozen=True)
class PatchCondition:
    """One patch and what the solver is told about it.

    ``patch_type`` is what `constant/polyMesh/boundary` says — not what the user asked for. It
    is carried
    because the two can disagree: a `symmetry` condition on a patch the mesher made a `wall` is
    a mistake
    worth refusing rather than writing, since the solver would read a symmetry condition on a
    wall and
    quietly produce a different flow.
    """

    name: str
    patch_type: str
    kind: str
    velocity: tuple[float, float, float] | None = None
    pressure: float | None = None
    #: kg/s through the whole patch, for a `mass_flow_inlet`; `None` for every other kind.
    mass_flow: float | None = None
    #: The energy equation's condition (ADR-0027), one of `THERMAL_KINDS`; `None` when energy is
    #: off or the patch needs none (a symmetry plane). Defaults keep a flow-only patch unchanged.
    thermal: str | None = None
    #: Kelvin: the fixed value, or the backflow value of an `inletOutlet` outlet.
    temperature: float | None = None
    #: W/m², positive into the fluid, for a `heatFlux` wall.
    heat_flux: float | None = None
    #: Metres: a pressure outlet's area-weighted centroid (`tag.anchor`), filled with the energy
    #: equation on. The `fluid` writer needs the outlet's height to write `p_rgh` there
    #: (ADR-0027 step 5).
    centroid: tuple[float, float, float] | None = None
    #: The turbulence group of an inlet or an outlet's backflow (ADR-0028), used only by the
    #: kOmegaSST writer. `turbulence_mode` is one of `TURBULENCE_MODES`; the other two are the
    #: fraction and the ratio or the length, whichever the mode names. `None` when unset.
    turbulence_mode: str | None = None
    intensity: float | None = None
    viscosity_ratio: float | None = None
    length_scale: float | None = None


#: The temperature conditions the snapshot can carry (ADR-0027 step 2). Convection walls are not
#: here on purpose: the snapshot refuses them with `solve.thermal_unsupported` until the writer can
#: express one.
THERMAL_KINDS: tuple[str, ...] = ("fixedValue", "zeroGradient", "inletOutlet", "heatFlux")

#: The snapshot fields that only the energy equation fills. `solve_basis` drops them when energy
#: is off, so a flow-only project hashes, and writes, exactly as it did before they existed.
ENERGY_FIELDS: tuple[str, ...] = ("energy", "mu", "cp", "kappa", "T_ref", "gravity", "p_ref")

#: The patch fields only a mass-flow inlet fills, dropped from the basis when `None` so a project
#: without one keeps its basis.
FLOW_FIELDS: tuple[str, ...] = ("mass_flow",)

#: The patch fields that only the energy equation fills, dropped from the basis when `None`.
THERMAL_FIELDS: tuple[str, ...] = ("thermal", "temperature", "heat_flux", "centroid")

#: The turbulence-group fields of a patch, dropped from the basis when `None` (ADR-0028), so a
#: laminar project's basis does not move.
TURBULENCE_FIELDS: tuple[str, ...] = (
    "turbulence_mode",
    "intensity",
    "viscosity_ratio",
    "length_scale",
)

#: The transient controls and their "off" values. Dropped from the basis while they hold them, so
#: a run made before they existed keeps its basis (the same rule as `ENERGY_FIELDS`).
TRANSIENT_CONTROL_DEFAULTS: dict[str, object] = {
    "max_courant": 0.0,
    "write_time": 0.0,
    "average": False,
    "average_start": 0.0,
}

#: The inflow turbulence modes the model offers (`geometry.model.TURBULENCE_INPUTS`).
TURBULENCE_MODES: tuple[str, ...] = ("intensity_ratio", "intensity_length")


@dataclass(frozen=True)
class SolveSnapshot:
    """Everything one steady incompressible run needs.

    ``iterations`` counts **iterations, not seconds**: an OpenFOAM steady run steps `deltaT 1`
    per outer
    iteration, so `endTime == iterations`.
    """

    settings_id: str
    engine: str
    turbulence: str
    iterations: int
    write_interval: int
    residual_target: float
    nu: float
    rho: float
    patches: tuple[PatchCondition, ...]
    #: The patches whose flow rate and mean pressure are reported. Inlets and outlets, normally.
    monitor_patches: tuple[str, ...] = field(default_factory=tuple)
    #: MPI ranks; one retains the serial recipe.
    cores: int = 1
    #: The mesh's max non-orthogonality is above `NON_ORTHO_LIMIT` (checkMesh's own number): the
    #: writers then limit the non-orthogonal correction and add a corrector. Measured on the mixing
    #: elbow: a tetrahedral mesh at 79.8 degrees diverged ("Negative initial temperature") at
    #: iteration 67 with plain `corrected`. Off, the case is unchanged (and so is its basis).
    non_orthogonal: bool = False
    #: The energy equation (ADR-0027). Off, every field below keeps its default and the case is
    #: the flow-only case; on, they are the material at `T_ref` and the solver settings, in SI.
    energy: bool = False
    #: Dynamic viscosity, Pa·s.
    mu: float = 0.0
    #: Specific heat, J/(kg·K).
    cp: float = 0.0
    #: Thermal conductivity, W/(m·K).
    kappa: float = 0.0
    #: The material's reference temperature, K: where `rho`, `mu`, `cp` and `kappa` were evaluated.
    T_ref: float = 300.0
    #: m/s², written to `constant/g`.
    gravity: tuple[float, float, float] = (0.0, 0.0, 0.0)
    #: The operating pressure, Pa, written to `constant/pRef`.
    p_ref: float = 101325.0

    #: Explicit thermodynamic closure; never inferred from a density threshold.
    density_model: str = "constant"
    #: Molecular mass in kg/mol (OF14 molWeight is converted at the writer boundary).
    molar_mass: float = 0.02897
    transient: bool = False
    delta_t: float = 0.001
    end_time: float = 1.0
    initial_velocity: float = 1.0
    initial_intensity: float = 0.05
    initial_length_scale: float = 0.01
    initial_viscosity_ratio: float = 10.0
    #: Transient only. Above zero, the time step adapts to keep the Courant number under this
    #: (`adjustTimeStep yes; maxCo`), starting from `delta_t`; zero keeps `delta_t` fixed.
    max_courant: float = 0.0
    #: Transient only. Above zero, fields are written every this many seconds of physical time;
    #: zero writes every `write_interval` time steps.
    write_time: float = 0.0
    #: Transient only. Time-average U and p (and the model's k or nut) from `average_start`,
    #: written as `UMean`, `pMean`, ... beside the instantaneous fields.
    average: bool = False
    average_start: float = 0.0

    def patch(self, name: str) -> PatchCondition:
        """One patch by name, or `KeyError` — the writer validates before it gets here."""
        for item in self.patches:
            if item.name == name:
                return item
        raise KeyError(name)


def laplacian_scheme(snap: SolveSnapshot) -> str:
    """The Laplacian scheme: limited on a mesh above `NON_ORTHO_LIMIT`, plain `corrected` otherwise.

    `limited corrected 0.33` keeps a third of the explicit non-orthogonal correction, the usual
    choice for a tetrahedral or polyhedral mesh near 80 degrees; on an ordinary mesh the case is
    the one it always was.
    """
    return (
        "Gauss linear limited corrected 0.33" if snap.non_orthogonal else "Gauss linear corrected"
    )


def sn_grad_scheme(snap: SolveSnapshot) -> str:
    """The surface-normal gradient scheme, limited by the same rule as `laplacian_scheme`."""
    return "limited corrected 0.33" if snap.non_orthogonal else "corrected"
